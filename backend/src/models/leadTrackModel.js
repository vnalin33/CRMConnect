const getLeadsByConnector = async (connectorId) => {
  const query = `
    SELECT 
      lp.id,
      lp.firstname,
      lp.lastname,
      lp.email,
      lp.mobilenumber,
      lp.loantype,
      lp.loanamount,
      lp.status AS lead_status,
      lp.createdon,
      lt.id AS track_id,
      lt.status AS track_status,
      lt.notes AS track_notes,
      lt.customername,
      lt.tracknumber,
      lt.modifyon AS track_modified,
      lt.disbursementamount,
      lt.payoutpercent
    FROM leadpersonaldetails lp
    LEFT JOIN leadtrackdetails lt ON lt.leadid = lp.id
    WHERE lp.connectorid = $1
    ORDER BY lp.createdon DESC
  `;
  const { rows } = await db.query(query, [connectorId]);
  return rows;
};

